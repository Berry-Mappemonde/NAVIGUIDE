"""
Routing Engine MPA (Marine Protected Area) Avoidance Validator.

Ensures vessel paths generated by the routing pipeline do not penetrate
zones classified as forbidden.
"""
from shapely.geometry import LineString, shape


def check_route_forbidden_mpas(route_geojson: dict, forbidden_mpas: list[dict]) -> dict:
    """
    Validates that a GeoJSON route LineString does not cross forbidden MPAs.

    Args:
        route_geojson: GeoJSON Feature or FeatureCollection of the vessel route.
        forbidden_mpas: List of GeoJSON features representing forbidden areas
                        (where entry or traffic is strictly prohibited).

    Returns:
        dict: A report detailing compliance status and any violations found.
    """
    violations = []
    features = route_geojson.get("features", [route_geojson])

    for f_idx, feat in enumerate(features):
        geom = feat.get("geometry", {})
        if geom.get("type") != "LineString":
            continue

        route_coords = geom.get("coordinates", [])
        if len(route_coords) < 2:
            continue

        route_line = LineString(route_coords)

        for mpa in forbidden_mpas:
            mpa_geom = mpa.get("geometry")
            if not mpa_geom:
                continue

            mpa_poly = shape(mpa_geom)
            if route_line.intersects(mpa_poly):
                violations.append({
                    "leg_index": f_idx,
                    "mpa_id": mpa.get("id") or mpa.get("properties", {}).get("name", "Unknown MPA"),
                    "category": "forbidden"
                })

    return {
        "status": "PASSED" if not violations else "FAILED",
        "is_compliant": len(violations) == 0,
        "violations_count": len(violations),
        "violations": violations
    }
